import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const out = join(dirname(fileURLToPath(import.meta.url)), '../docs/qa/L76-LOCK-TERMS');
mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
await page.goto('http://127.0.0.1:8080/', { waitUntil: 'domcontentloaded', timeout: 30000 });
await page.waitForTimeout(800);
await page.waitForSelector('#hvLoginRoot.is-open, #hvLoginRoot:not([hidden])', { timeout: 8000 }).catch(() => {});
const agree = await page.locator('.hv-login-agree').first().textContent();
const agreeBox = await page.locator('.hv-login-agree').first().boundingBox();
const quotesInText = /"/.test(agree || '');
await page.screenshot({ path: join(out, 'login-terms-390x844.png'), fullPage: false });
await page.locator('#hvLoginContinue').click();
await page.waitForTimeout(900);
await page.locator('#hubScreen .art-dock [data-art-go="daily"]').first().click();
await page.waitForSelector('#hvLichRoot.is-open', { timeout: 6000 });
await page.waitForTimeout(300);
const campaignLock = await page.locator('[data-lich-spoke="campaign"] .hv-lich-lock').count();
const holdLock = await page.locator('[data-lich-spoke="hold"] .hv-lich-lock').count();
const palaceSrc = await page.locator('[data-lich-spoke="palace"] img').getAttribute('src');
await page.screenshot({ path: join(out, 'lich-wheel-390x844.png'), fullPage: false });
await browser.close();
const oneLine = !!(agreeBox && agreeBox.height <= 22);
const ok = !quotesInText && /Thỏa thuận người dùng/.test(agree) && /Chính sách bảo mật/.test(agree) && campaignLock === 0 && holdLock === 1;
console.log(JSON.stringify({ agree, agreeH: agreeBox && agreeBox.height, oneLine, campaignLock, holdLock, palaceSrc, ok }, null, 2));
if (!ok) process.exit(1);
